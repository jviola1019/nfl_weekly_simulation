/**
 * The data model as a Mermaid erDiagram, generated from the Drizzle schema (src/db/schema.ts).
 * `npm run erd` writes it to docs/ERD.md, and src/lib/erd.test.ts fails when that file is stale,
 * so the diagram can never drift from the tables the app migrates.
 */
import { is } from "drizzle-orm";
import { getTableConfig, PgTable, type PgColumn } from "drizzle-orm/pg-core";
import * as schema from "../db/schema";

const HEADER = `# Data model (ERD)

Generated by \`npm run erd\` from \`web/src/db/schema.ts\`; do not edit by hand (\`npm run erd\` rewrites it and \`web/src/lib/erd.test.ts\` fails when it is stale). It is the column list the 2026-09-28 design spec (§3) promised as \`docs/data-contract.md\`. The invariants SQL enforces are in \`web/drizzle/0001_invariants.sql\`; the checks run after every ingest are \`npm run db-check\` (\`web/src/lib/dbcheck/checks.ts\`).

Keys: PK primary key, FK foreign key, UK unique. A relationship drawn \`|o--o{\` has a nullable foreign key.
`;

/** SQL types with a space get a one-word name; Mermaid attribute types cannot contain spaces. */
const TYPE_NAMES: Record<string, string> = { "timestamp with time zone": "timestamptz", "double precision": "float8" };

function erdType(sqlType: string): string {
  const name = TYPE_NAMES[sqlType] ?? sqlType;
  if (/\s/.test(name)) throw new Error(`renderErd: no ERD name for SQL type ${sqlType}`);
  return name;
}

export function renderErd(): string {
  const tables = Object.values(schema)
    .filter((v: unknown): v is PgTable => is(v, PgTable))
    .map((t) => getTableConfig(t))
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const entities: string[] = [];
  const relationships: Array<{ key: string; line: string }> = [];
  for (const t of tables) {
    const pk = new Set([...t.columns.filter((c) => c.primary).map((c) => c.name), ...t.primaryKeys.flatMap((p) => p.columns.map((c) => c.name))]);
    const fk = new Set(t.foreignKeys.flatMap((f) => f.reference().columns.map((c) => c.name)));
    const uk = new Set([
      ...t.columns.filter((c) => c.isUnique).map((c) => c.name),
      ...t.indexes
        .filter((i) => i.config.unique && i.config.columns.length === 1)
        .map((i) => (i.config.columns[0] as PgColumn).name)
    ]);
    entities.push(`  ${t.name} {`);
    for (const c of t.columns) {
      const keys = [pk.has(c.name) && "PK", fk.has(c.name) && "FK", uk.has(c.name) && "UK"].filter(Boolean).join(", ");
      entities.push(`    ${erdType(c.getSQLType())} ${c.name}${keys ? ` ${keys}` : ""}`);
    }
    entities.push("  }");
    for (const f of t.foreignKeys) {
      const ref = f.reference();
      const parent = getTableConfig(ref.foreignTable).name;
      const cols = ref.columns.map((c) => c.name);
      const optional = ref.columns.some((c) => !c.notNull);
      relationships.push({ key: `${parent}|${t.name}|${cols.join(",")}`, line: `  ${parent} ${optional ? "|o--o{" : "||--o{"} ${t.name} : "${cols.join(", ")}"` });
    }
  }
  relationships.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  return [HEADER, "```mermaid", "erDiagram", ...entities, ...relationships.map((r) => r.line), "```", ""].join("\n");
}
