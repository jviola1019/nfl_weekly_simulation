# =============================================================================
# Render docs/VARIABLE_LEDGER.md (design 2026-10-20 §5) from the registry and
# the committed VVF results, one run per anchor. ASCII only, so the generated
# bytes are the same on every OS. scripts/write_variable_ledger.R writes it;
# tests/testthat/test-vvf-ledger.R fails when the document and this render differ.
# =============================================================================

# Committed VVF runs whose results the ledger shows, one per anchor
VVF_LEDGER_RUNS <- data.table::data.table(
  anchor = "close", decision = "close", stages = "S1, S2", window = "Tune 2018-2022",
  dir = "reports/2026-10-22/vvf-v2-repro")

vvf_md_cell <- function(x) {
  x <- as.character(x)
  x[is.na(x) | !nzchar(x)] <- "-"
  gsub("|", "\\|", gsub("\n", " ", x, fixed = TRUE), fixed = TRUE)
}

vvf_md_table <- function(header, rows) {
  c(paste0("| ", paste(header, collapse = " | "), " |"),
    paste0("|", paste(rep("---", length(header)), collapse = "|"), "|"),
    vapply(rows, function(r) paste0("| ", paste(vvf_md_cell(r), collapse = " | "), " |"), character(1)))
}

vvf_defect_ids <- function(ds) if (length(ds)) paste(vapply(ds, `[[`, "", "id"), collapse = ", ") else "-"

#' One anchor's results, keyed by feature
vvf_ledger_results <- function(run) {
  s1 <- vvf_read_csv(file.path(run$dir, "s1_features.csv"))
  vif <- vvf_read_csv(file.path(run$dir, "s2_vif.csv"))[family == "outcome"]
  st <- vvf_read_csv(file.path(run$dir, "s2_stability.csv"))[family == "outcome"]
  meta <- jsonlite::read_json(file.path(run$dir, "run_meta.json"))
  q <- function(f, fam) {
    v <- s1[feature == f & family == fam, q_bh]
    if (!length(v) || !is.finite(v)) "n/a" else sprintf("%.3f", v)
  }
  reasons <- strsplit(vif$reasons, "; ", fixed = TRUE)[[1]]
  vif_note <- function(f) {
    hit <- reasons[startsWith(reasons, paste0(f, ": "))]
    if (length(hit)) paste("dropped,", sub("^[^:]+: ", "", hit)) else "kept"
  }
  feats <- unique(s1$feature)
  out <- lapply(feats, function(f) {
    sr <- st[feature == f]
    list(s1 = sprintf("%s / %s / %s", q(f, "outcome"), q(f, "spread"), q(f, "total")),
         s2 = sprintf("VIF %s; signs %s; x season p %s", vif_note(f),
                      if (nrow(sr) && isTRUE(sr$sign_consistent)) "stable" else "not stable",
                      if (nrow(sr)) sprintf("%.3f", sr$int_p) else "n/a"))
  })
  list(by_feature = setNames(out, feats), sha = meta$result_sha256)
}

vvf_render_ledger <- function(registry = vvf_registry(), runs = VVF_LEDGER_RUNS, disclosures = vvf_disclosures()) {
  res <- lapply(seq_len(nrow(runs)), function(i) vvf_ledger_results(runs[i]))
  names(res) <- runs$anchor
  lines <- c(
    "# Variable ledger",
    "",
    paste("Generated by `scripts/write_variable_ledger.R` from `backtest/vvf/registry.R` and the committed VVF results.",
          "Do not edit it by hand: change the registry, re-run the script, and commit both.",
          "`tests/testthat/test-vvf-ledger.R` fails when they disagree."),
    "",
    paste("Every variable has a row: its definition, source, when it becomes known (`known_at`), its unit test,",
          "its parameter count, its known defects with the phase that fixes each, and its latest results per anchor.",
          "A stage refuses any feature without a row or known after the decision (`vvf_assert_known_at()`)."),
    "",
    "## When a variable becomes known",
    "",
    vvf_md_table(c("Class", "Becomes known"), lapply(seq_len(nrow(VVF_KNOWN_AT)), function(i) {
      c(paste0("`", VVF_KNOWN_AT$class[i], "`"), VVF_KNOWN_AT$becomes_known[i])
    })),
    "",
    "A post-hoc variable is refused at every decision point.",
    "",
    "## Decision points",
    "",
    vvf_md_table(c("Decision", "Information set", "Price", "Use"), lapply(seq_len(nrow(VVF_DECISION_INFO)), function(i) {
      dn <- VVF_DECISION_INFO$decision[i]
      c(paste0("`", dn, "`"), paste(VVF_DECISIONS[[dn]], collapse = ", "), VVF_DECISION_INFO$price[i], VVF_DECISION_INFO$use[i])
    })),
    "",
    "## Results shown",
    "",
    vvf_md_table(c("Anchor", "Decision", "Stages", "Window", "Run", "result_sha256"), lapply(seq_len(nrow(runs)), function(i) {
      c(runs$anchor[i], runs$decision[i], runs$stages[i], runs$window[i], paste0("`", runs$dir[i], "`"), res[[i]]$sha)
    })),
    "",
    paste("S1 columns are the BH q-values within each family: outcome (moneyline, LR test with the anchor as offset),",
          "spread and total (F tests on the residual against the line). q < 0.05 is a signal; anything else is",
          "\"no evidence\" at the MDE in the run's `s1_features.csv`. S2 shows the VIF step (VIF <= 5, the",
          "declared-first feature kept), whether the effect's sign is the same in every season, and the",
          "feature x season LR test, all for the outcome family. The opener anchor has no run yet: its inputs",
          "come from D1's archive (A4)."),
    "",
    "## Features",
    "",
    vvf_md_table(c("Variable", "Group", "Definition", "Source", "known_at", "Params", "S1 close (q: outcome / spread / total)",
                   "S2 close (outcome)", "Defects", "Unit test"),
                 lapply(which(registry$kind == "feature"), function(i) {
                   r <- registry[i]
                   got <- res$close$by_feature[[r$name]]
                   c(paste0("`", r$name, "`"), r$group, r$definition, r$source,
                     paste0(r$known_at, if (r$posthoc) " (post-hoc)" else ""), r$n_params,
                     if (is.null(got)) (if (r$posthoc) "not screened (post-hoc)" else "not screened") else got$s1,
                     if (is.null(got)) "-" else got$s2, vvf_defect_ids(r$defects[[1]]), r$unit_test)
                 })),
    "",
    "## Engine variables, settings and market inputs",
    "",
    vvf_md_table(c("Variable", "Kind", "Group", "Definition", "Source", "known_at", "Params", "Defects", "Evidence", "Unit test"),
                 lapply(which(registry$kind != "feature"), function(i) {
                   r <- registry[i]
                   c(paste0("`", r$name, "`"), r$kind, r$group, r$definition, r$source,
                     paste0(r$known_at, if (r$posthoc) " (post-hoc)" else ""),
                     if (is.na(r$n_params)) "not counted yet (G1)" else r$n_params,
                     vvf_defect_ids(r$defects[[1]]), r$evidence, r$unit_test)
                 })),
    "",
    "## Defects",
    "",
    vvf_md_table(c("ID", "Variable", "Defect", "Fix", "Phase", "Status", "Audit"),
                 unlist(lapply(seq_len(nrow(registry)), function(i) {
                   lapply(registry$defects[[i]], function(d) c(d$id, paste0("`", registry$name[i], "`"), d$text, d$fix,
                                                             d$phase, d$status, d$audit))
                 }), recursive = FALSE)),
    "",
    "## Disclosures",
    "",
    vvf_md_table(c("ID", "Disclosure", "Source"), lapply(seq_len(nrow(disclosures)), function(i) {
      c(disclosures$id[i], disclosures$text[i], disclosures$source[i])
    }))
  )
  lines
}
