# Run from the repository root.
suppressPackageStartupMessages(library(data.table))
dir <- file.path("reports", "2026-10-28", "a3-research")
rd <- function(f) fread(file.path(dir, f))
f3 <- function(x) sprintf("%.3f", x)
rng <- function(x) sprintf("%s-%s", f3(min(x, na.rm = TRUE)), f3(max(x, na.rm = TRUE)))
say <- function(...) cat(sprintf(...), "\n", sep = "")

say("# A3 research summary (generated by scripts/research-summary.R)")

say("\n## 1. The S4 null")
dg <- rd("s4-null-diagnostic.csv")
say("diagnostic (B = 2000, Tune 2018-2022, %d features): y shuffled within week: %d intervals wholly above 0; x permuted within week: %d above, %d wholly below",
    nrow(dg), sum(dg$y_shuffle_lo > 0), sum(dg$x_shuffle_lo > 0), sum(dg$x_shuffle_hi < 0))
say("diagnostic: correlation of the y-shuffle skill with |cor(x, anchor)|: %s", f3(stats::cor(dg$y_shuffle_skill, abs(dg$cor_with_anchor), use = "complete.obs")))
say("diagnostic: largest y-shuffle skills: %s", dg[order(-y_shuffle_skill)][1:3, paste(sprintf("%s %s", feature, f3(y_shuffle_skill)), collapse = ", ")])
nl <- rd("s4_nulls.csv")
s <- nl[, .(reps = .N, mean_above = mean(above), max_above = max(above), mean_below = mean(below),
            reps_with_claim = sum(claims > 0), claims = sum(claims), reps_spec_fail = sum(above + below > 0)), by = null]
for (i in seq_len(nrow(s))) say("null '%s': %d replicates x %d features (B = 1000); intervals wholly above 0 per replicate: mean %.1f, max %d; wholly below 0: mean %.1f; replicates with a claim: %d; claims in all: %d; replicates failing the spec's 'every interval includes 0': %d",
                                s$null[i], s$reps[i], nrow(dg), s$mean_above[i], s$max_above[i], s$mean_below[i], s$reps_with_claim[i], s$claims[i], s$reps_spec_fail[i])
pw <- rd("s4_power.csv")
p <- pw[, .(detected = sum(claim), reps = .N, mean_skill = mean(skill)), by = beta]
p[, c("ci_lo", "ci_hi") := as.list(stats::binom.test(detected, reps)$conf.int), by = beta]
for (i in seq_len(nrow(p))) say("power: planted beta %.2f per SD of rest_diff: detected %d of %d (exact 95%% CI %.2f-%.2f), mean skill %.5f",
                                p$beta[i], p$detected[i], p$reps[i], p$ci_lo[i], p$ci_hi[i], p$mean_skill[i])

say("\n## 2. The joint test (null size at alpha = 0.05; 1,000 draws, 999 Rademacher draws each)")
jo <- rd("joint_size.csv")[set != "situational, one season"]
for (t in unique(jo$test)) say("outcome, 107 week clusters, k 29-34, week SD 0-0.2: %-15s size %s", t, rng(jo[test == t, size]))
one <- rd("joint_size.csv")[set == "situational, one season"]
say("outcome, one season (%d clusters, k %d, %d draws): lr %s; score_boot_diag %s; the cluster-robust Wald and the full score bootstrap are undefined (k > G - 1)",
    one$G[1], one$k[1], one[test == "score_boot_diag", n_ok], f3(one[test == "lr", size]), f3(one[test == "score_boot_diag", size]))
li <- rd("joint_size_linear.csv")
for (fm in unique(li$family)) for (t in unique(li$test)) say("%s, 107 week clusters, k 29-34, week SD 0-2 points: %-15s size %s", fm, t, rng(li[family == fm & test == t, size]))
mc <- sqrt(0.05 * 0.95 / 1000)
say("Monte Carlo 95%% band for a true size of 0.05 with 1,000 draws: %s-%s", f3(0.05 - 1.96 * mc), f3(0.05 + 1.96 * mc))
mc5 <- sqrt(0.05 * 0.95 / 500)
say("Monte Carlo 95%% band for a true size of 0.05 with 500 draws (the one-season row): %s-%s", f3(0.05 - 1.96 * mc5), f3(0.05 + 1.96 * mc5))

say("\n## 3. The cluster unit")
ic <- rd("cluster_icc.csv")
for (i in seq_len(nrow(ic))) say("ICC %-9s by %-14s (%3d groups): %.4f (F %.3f, p %.3f)", ic$residual[i], ic$unit[i], ic$groups[i], ic$icc[i], ic$F[i], ic$p[i])
de <- rd("cluster_design_effects.csv")
for (u in setdiff(names(de), "feature")) say("design effect of clustering by %-17s over HC0, %d features: median %s, range %s", u, nrow(de), f3(stats::median(de[[u]])), rng(de[[u]]))

say("\n## 4. Late schedule changes")
fg <- rd(file.path("data", "flex-games.csv"))
say("changed games 2018-2024 (Wikipedia 'Scheduling changes', %d rows): %s", nrow(fg), fg[, .N, by = kind][order(-N), paste(sprintf("%s %d", kind, N), collapse = ", ")])
ctx <- fread(file.path("backtest", "vvf", "data", "game_context.csv"), select = c("game_id", "season"))
n_tune <- ctx[season %in% 2018:2022, .N]
lt <- rd("late_tests.csv")
for (i in seq_len(nrow(lt))) say("%-16s %3d of %d Tune games (%.1f%%): moneyline log-odds against the close %+.3f (LR p %.3f, robust p %.3f); ATS %+.2f points (robust p %.3f)",
                                 lt$indicator[i], lt$n_flag[i], n_tune, 100 * lt$n_flag[i] / n_tune, lt$outcome_logodds[i], lt$outcome_p_lr[i],
                                 lt$outcome_p_robust[i], lt$ats_points[i], lt$ats_p_robust[i])
ls1 <- rd("late_s1_sensitivity.csv")
say("S1 with the changed games out: %d of %d verdicts change; smallest q without them %s (%s)", sum(ls1$verdict_changed), nrow(ls1),
    f3(min(ls1$q_out, na.rm = TRUE)), ls1[which.min(q_out), paste(family, feature)])
mv <- rd("late_movement.csv")
for (i in seq_len(nrow(mv))) say("opener-to-close movement 2023-2024, %s %s: flagged %d (mean %.3f) vs other %d (mean %.3f); permutation p %.3f",
                                 mv$indicator[i], mv$measure[i], mv$n_flag[i], mv$mean_flag[i], mv$n_other[i], mv$mean_other[i], mv$perm_p[i])
